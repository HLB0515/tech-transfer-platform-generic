def main():
    path = Path("data/store.json")
    backup_dir = Path("backups") / f"before-agent-question-update-{datetime.now().strftime('%Y%m%d-%H%M%S')}"
    backup_dir.mkdir(parents=True, exist_ok=True)
    backup = backup_dir / "store.json"
    shutil.copy2(path, backup)
    store = json.loads(path.read_text(encoding="utf-8"))
    enriched = []
    for index, agent in enumerate(AGENTS, start=1):
        enriched.append({
            "id": index,
            **agent,
            "order": index,
            "enabled": True,
        })
    store["agents"] = enriched
    store["agentTrainingVersion"] = "agent-square-design-20260703"
    path.write_text(json.dumps(store, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"agents": len(enriched), "backup": str(backup)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
